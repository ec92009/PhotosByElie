import { createStoredZipBytes } from "./zip-utils.mjs";

const safeName = (value, fallback) => String(value || fallback)
  .replace(/[^A-Za-z0-9._-]+/g, "-")
  .replace(/^-+|-+$/g, "")
  .slice(0, 120) || fallback;

const extensionFor = (path) => {
  const match = String(path || "").match(/\.([A-Za-z0-9]+)$/);
  return match ? match[1].toLowerCase() : "jpg";
};

const basename = (path) => String(path || "").split(/[\\/]/).pop();

const renderedJpgKey = (item, product) =>
  `renders/${safeName(item.photoId, "photo")}/${safeName(basename(item.source.path), "source")}-${safeName(product.id, "product")}.jpg`;

const orderManifest = (order, rendered) => [
  "Photos By Elie digital delivery",
  "",
  `Order ID: ${order.id}`,
  `Buyer email: ${order.buyerEmail}`,
  `Amount paid: ${order.currency.toUpperCase()} ${(Number(order.amountPaid || order.amountExpected) / 100).toFixed(2)}`,
  "",
  ...rendered.flatMap((entry) => [
    `Photo ID: ${entry.photoId}`,
    `Title: ${entry.title}`,
    ...(entry.keywords?.length ? [`Keywords: ${entry.keywords.join(", ")}`] : []),
    `Product: ${entry.productLabel}`,
    `Delivered file: ${entry.name}`,
    `Private source key: ${entry.sourceKey}`,
    ...(entry.renderKey ? [
      `Private render cache key: ${entry.renderKey}`,
      `Private render cache: ${entry.cacheHit ? "hit" : "created"}`,
    ] : []),
    "",
  ]),
  "Delivery note: generated by the mock payment Worker from private R2 developed masters.",
  "",
].join("\n");

export const createR2ZipDelivery = ({
  privateBucket,
  deliveryBucket = privateBucket,
  renderer = null,
  now = () => new Date(),
  randomUUID = () => crypto.randomUUID(),
} = {}) => {
  if (!privateBucket) throw new Error("createR2ZipDelivery requires a privateBucket R2 binding.");
  if (!deliveryBucket) throw new Error("createR2ZipDelivery requires a deliveryBucket R2 binding.");

  const createDelivery = async (order) => {
    const rendered = [];
    const entries = [];

    const getOrCreateRenderedJpg = async ({ item, product, sourceBytes }) => {
      const renderKey = renderedJpgKey(item, product);
      const cached = await deliveryBucket.get(renderKey);
      if (cached) {
        return {
          data: new Uint8Array(await cached.arrayBuffer()),
          renderKey,
          cacheHit: true,
        };
      }
      const canRender = renderer && typeof renderer.canRender === "function" && renderer.canRender(product.id);
      if (!canRender) {
        throw Object.assign(new Error(`Private render is missing: ${renderKey}. Generate and upload the unwatermarked ${product.id} deliverable before checkout can complete.`), {
          status: 409,
          code: "missing_private_render",
        });
      }

      const data = await renderer.render({
        sourceBytes,
        sourceKey: item.source.privateMasterKey,
        product,
        item,
      });
      await deliveryBucket.put(renderKey, data, {
        httpMetadata: {
          contentType: "image/jpeg",
          contentDisposition: `attachment; filename="${safeName(item.photoId, "photo")}-${safeName(product.id, "product")}.jpg"`,
        },
        customMetadata: {
          photoId: item.photoId,
          productId: product.id,
          title: item.title || "",
          keywords: (item.keywords || []).join(", "),
          sourceKey: item.source.privateMasterKey,
          generatedAt: now().toISOString(),
          watermark: "none",
        },
      });
      return { data, renderKey, cacheHit: false };
    };

    for (const item of order.items) {
      const object = await privateBucket.get(item.source.privateMasterKey);
      if (!object) {
        throw Object.assign(new Error(`Private R2 master is missing: ${item.source.privateMasterKey}`), {
          status: 409,
          code: "missing_private_master",
        });
      }
      const sourceBytes = new Uint8Array(await object.arrayBuffer());

      for (const product of item.products) {
        const isFullResolution = product.id === "full";
        const data = isFullResolution
          ? sourceBytes
          : await getOrCreateRenderedJpg({ item, product, sourceBytes });
        const ext = isFullResolution ? extensionFor(item.source.path) : "jpg";
        const name = `${safeName(item.photoId, "photo")}-${safeName(product.id, "product")}.${ext}`;
        entries.push({ name, data: isFullResolution ? data : data.data });
        rendered.push({
          photoId: item.photoId,
          title: item.title,
          keywords: item.keywords || [],
          productId: product.id,
          productLabel: product.label,
          sourceKey: item.source.privateMasterKey,
          name,
          renderKey: isFullResolution ? "" : data.renderKey,
          cacheHit: !isFullResolution && data.cacheHit,
        });
      }
    }

    entries.push({ name: "ORDER.txt", data: orderManifest(order, rendered) });
    const zipKey = `deliveries/photosbyelie-order-${order.id}.zip`;
    const zipBytes = createStoredZipBytes(entries, now());
    await deliveryBucket.put(zipKey, zipBytes, {
      httpMetadata: {
        contentType: "application/zip",
        contentDisposition: `attachment; filename="photosbyelie-order-${order.id}.zip"`,
      },
      customMetadata: {
        orderId: order.id,
        buyerEmail: order.buyerEmail,
        generatedAt: now().toISOString(),
      },
    });

    const token = `dl_${randomUUID().replace(/-/g, "").slice(0, 28)}`;
    return {
      zipKey,
      token,
      downloadUrl: `/download/${token}`,
      readyAt: now().toISOString(),
      items: rendered.map((entry) => ({
        photoId: entry.photoId,
        products: [entry.productId],
        sourceKey: entry.sourceKey,
        output: entry.name,
        renderKey: entry.renderKey || undefined,
        cacheHit: entry.renderKey ? entry.cacheHit : undefined,
      })),
    };
  };

  const getDownloadResponse = async (downloadRecord) => {
    const object = await deliveryBucket.get(downloadRecord.zipKey);
    if (!object) {
      return new Response(JSON.stringify({
        error: {
          code: "missing_delivery_zip",
          message: "The delivery ZIP was not found in private storage.",
        },
      }, null, 2), {
        status: 404,
        headers: {
          "content-type": "application/json; charset=utf-8",
          "access-control-allow-origin": "*",
        },
      });
    }
    return new Response(object.body, {
      headers: {
        "access-control-allow-origin": "*",
        "content-type": object.httpMetadata?.contentType || "application/zip",
        "content-disposition": object.httpMetadata?.contentDisposition || `attachment; filename="${downloadRecord.zipKey.split("/").pop() || "photosbyelie-order.zip"}"`,
      },
    });
  };

  return {
    createDelivery,
    getDownloadResponse,
  };
};
